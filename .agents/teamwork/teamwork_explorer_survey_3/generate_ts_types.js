import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const defs = JSON.parse(fs.readFileSync(path.join(__dirname, 'definitions.json'), 'utf8'));

function swaggerTypeToTs(prop, defs) {
  if (prop.$ref) {
    const name = prop.$ref.replace('#/definitions/', '').split('.').pop();
    return name;
  }
  if (prop.type === 'string') {
    if (prop.enum) {
      return prop.enum.map(e => `'${e}'`).join(' | ');
    }
    return 'string';
  }
  if (prop.type === 'integer' || prop.type === 'number') {
    if (prop.enum) {
      return prop.enum.join(' | ');
    }
    return 'number';
  }
  if (prop.type === 'boolean') return 'boolean';
  if (prop.type === 'array') {
    if (prop.items) {
      return `${swaggerTypeToTs(prop.items, defs)}[]`;
    }
    return 'unknown[]';
  }
  if (prop.type === 'object') {
    return 'Record<string, unknown>';
  }
  return 'unknown';
}

const lines = [
  '/**',
  ' * AUTOGENERATED RESCUEBYTE BACKEND TYPES MATCHING SWAGGER/OPENAPI CONTRACT',
  ' * Base URL: https://dolpin-fourthree.bccdev.id/',
  ' */\n'
];

for (const [key, def] of Object.entries(defs)) {
  const shortName = key.split('.').pop();
  
  if (def.enum) {
    // Enum type
    const varNames = def['x-enum-varnames'] || [];
    const values = def.enum.map((val, idx) => {
      const vname = varNames[idx] || `Val_${val}`;
      const vtype = typeof val === 'string' ? `'${val}'` : val;
      return `  ${vname} = ${vtype},`;
    }).join('\n');
    lines.push(`export enum ${shortName} {\n${values}\n}\n`);
    lines.push(`export type ${shortName}Type = ${def.enum.map(v => typeof v === 'string' ? `'${v}'` : v).join(' | ')};\n`);
    continue;
  }

  if (def.type === 'object') {
    const props = def.properties || {};
    const required = def.required || [];
    const fields = Object.entries(props).map(([propName, propDef]) => {
      const isReq = required.includes(propName);
      const tsType = swaggerTypeToTs(propDef, defs);
      const desc = propDef.description ? `  /** ${propDef.description} */\n` : '';
      return `${desc}  ${propName}${isReq ? '' : '?'}: ${tsType};`;
    }).join('\n');

    lines.push(`export interface ${shortName} {\n${fields}\n}\n`);
  }
}

fs.writeFileSync(path.join(__dirname, 'swagger_types.ts'), lines.join('\n'));
console.log('Successfully generated swagger_types.ts!');
